"""把回测结果导出为终端可读格式:
1. results/{name}.json           — 完整报告(存档)
2. terminal/data.js              — REPORTS 数组(file:// 下免 CORS,双击即开)
schema 见 terminal/README-schema.md。新策略跑完 → export_one() 追加即可。
"""
import json, os, glob
import numpy as np
import pandas as pd

BASE = os.environ.get("FACTORLAB_ROOT", os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RESULTS = f"{BASE}/results"
TERMINAL = f"{BASE}/terminal"

def export_one(report: dict):
    """report dict(schema 见 README)→ 落盘 JSON + 重建 data.js。"""
    os.makedirs(RESULTS, exist_ok=True)
    name = report['meta']['key']
    with open(f"{RESULTS}/{name}.json", 'w', encoding='utf-8') as f:
        json.dump(report, f, ensure_ascii=False, indent=1)
    rebuild_datajs()
    print(f"exported: {name}")

def rebuild_datajs():
    reports = []
    for fp in sorted(glob.glob(f"{RESULTS}/*.json")):
        with open(fp, encoding='utf-8') as f:
            reports.append(json.load(f))
    with open(f"{TERMINAL}/data.js", 'w', encoding='utf-8') as f:
        f.write("// AUTO-GENERATED by export.py — do not edit\n")
        f.write("const REPORTS = ")
        json.dump(reports, f, ensure_ascii=False)
        f.write(";\n")
    print(f"data.js rebuilt with {len(reports)} reports")

def nav_payload(nav: pd.Series, bench: pd.Series = None):
    nav = nav.sort_index()
    out = {'dates': [d.strftime('%Y-%m-%d') for d in nav.index],
           'strategy': [round(float(v), 4) for v in nav.values]}
    if bench is not None:
        b = bench.reindex(nav.index).ffill()
        b = b / b.iloc[0]
        out['benchmark'] = [round(float(v), 4) for v in b.values]
    return out

def annual_payload(nav: pd.Series, bench: pd.Series = None):
    nav = nav.sort_index()
    s_ret = nav.groupby(nav.index.year).last() / nav.groupby(nav.index.year).first() - 1
    rows = []
    for y, s in s_ret.items():
        row = {'year': int(y), 'strategy': round(float(s), 4)}
        if bench is not None:
            b = bench.reindex(nav.index).ffill().dropna()
            by = b[b.index.year == y]
            if len(by) > 1:
                bs_ = by.iloc[-1] / by.iloc[0] - 1
                row['benchmark'] = round(float(bs_), 4)
                row['excess'] = round(float(s - bs_), 4)
        rows.append(row)
    return rows

def ic_payload(ic: pd.Series):
    return {'dates': [d.strftime('%Y-%m-%d') for d in ic.index],
            'values': [round(float(v), 4) for v in ic.values],
            'mean': float(ic.mean()), 'icir': float(ic.mean() / ic.std()) if ic.std() > 0 else 0,
            't': float(ic.mean() / (ic.std() / np.sqrt(len(ic)))) if ic.std() > 0 else 0,
            'n': int(len(ic))}

def layers_payload(layer_navs: dict):
    ks = sorted(layer_navs)
    first = layer_navs[ks[0]].sort_index()
    dates = [d.strftime('%Y-%m-%d') for d in first.index]
    series = []
    for k in ks:
        s = layer_navs[k].sort_index().reindex(first.index).ffill()
        s = s / s.iloc[0]
        series.append([round(float(v), 4) for v in s.values])
    return {'dates': dates, 'names': [f'Q{k}' for k in ks], 'series': series}

if __name__ == '__main__':
    rebuild_datajs()
